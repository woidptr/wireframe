const std = @import("std");
const target = @import("target.zig");

const Arch = target.Arch;
const BootLoader = target.BootLoader;

pub fn generate(b: *std.Build, arch: Arch, boot: BootLoader) std.Build.LazyPath {
    const l = target.layout(arch);

    const script = b.fmt(
        \\/* GENERATED by build/linker.zig — do not edit. */
        \\
        \\OUTPUT_FORMAT({[format]s})
        \\ENTRY(_start)
        \\
        \\PHDRS
        \\{{
        \\    text    PT_LOAD    FLAGS((1 << 0) | (1 << 2)) ; /* R + X */
        \\    rodata  PT_LOAD    FLAGS((1 << 2)) ;            /* R     */
        \\    data    PT_LOAD    FLAGS((1 << 1) | (1 << 2)) ; /* R + W */
        \\}}
        \\
        \\SECTIONS
        \\{{
        \\    . = {[base]d};
        \\    __kernel_start = .;
        \\
        \\{[pre_text]s}    __text_start = .;
        \\    .text : {{
        \\        *(.text .text.*)
        \\    }} :text
        \\    . = ALIGN({[page]d});
        \\    __text_end = .;
        \\
        \\    __rodata_start = .;
        \\    .rodata : {{
        \\{[rodata_extra]s}        *(.rodata .rodata.*)
        \\    }} :rodata
        \\    . = ALIGN({[page]d});
        \\    __rodata_end = .;
        \\
        \\    __data_start = .;
        \\    .data : {{
        \\{[data_extra]s}        *(.data .data.*)
        \\    }} :data
        \\
        \\    .bss : {{
        \\        *(COMMON)
        \\        *(.bss .bss.*)
        \\    }} :data
        \\    . = ALIGN({[page]d});
        \\    __data_end = .;
        \\
        \\    __kernel_end = .;
        \\
        \\    ASSERT(__kernel_end - __kernel_start < {[max_size]d},
        \\           "kernel image exceeds maximum size")
        \\
        \\    /DISCARD/ : {{
        \\        *(.eh_frame*)
        \\        *(.note .note.*)
        \\        *(.interp)
        \\        *(.comment)
        \\    }}
        \\}}
        \\
    , .{
        .format = l.output_format,
        .base = l.base,
        .page = l.page,
        .pre_text = preText(boot),
        .rodata_extra = rodataExtra(boot),
        .data_extra = dataExtra(boot),
        .max_size = max_image_size,
    });

    const wf = b.addWriteFiles();
    return wf.add("linker.ld", script);
}

const max_image_size: u64 = 16 * 1024 * 1024;

fn preText(boot: BootLoader) []const u8 {
    return switch (boot) {
        .limine => "",
    };
}

fn rodataExtra(boot: BootLoader) []const u8 {
    return switch (boot) {
        .limine => "",
    };
}

fn dataExtra(boot: BootLoader) []const u8 {
    return switch (boot) {
        .limine =>
        \\        KEEP(*(.limine_requests))
        \\
        ,
    };
}
